"""Generate golden vectors from the validated Python engine.

Every value the C++ port must reproduce is produced here, by the Python engine
that was already checked against the Swiss Ephemeris.  The C++ test suite then
has to match these to 1e-6 degrees -- so the two engines cannot silently drift.

Usage:  .venv311/Scripts/python.exe cpp/tools/gen_golden.py > cpp/tests/golden_vectors.h
"""
import datetime as dt
import json
import sys

sys.path.insert(0, "src")

from vyas import ephem, dasha, varga, ashtakavarga  # noqa: E402
from vyas.chart import Chart, PlanetState  # noqa: E402

UTC = dt.timezone.utc

CASES = [
    # (label, local birth datetime, tz hours east, latitude, longitude)
    ("jaipur_1990", dt.datetime(1990, 5, 15, 14, 35), 5.5, 26.9124, 75.7873),
    ("delhi_2000", dt.datetime(2000, 1, 1, 12, 0), 5.5, 28.6139, 77.2090),
    ("mumbai_1975", dt.datetime(1975, 8, 15, 6, 45), 5.5, 19.0760, 72.8777),
    ("london_1960", dt.datetime(1960, 3, 20, 4, 10), 0.0, 51.5074, -0.1278),
]


def chart_for(local_dt, tz, lat, lon):
    utc = ephem.local_to_utc(local_dt, tz)
    pos = ephem.planet_positions(utc)
    asc = ephem.ascendant_sidereal(utc, lat, lon)
    chart = Chart(asc, {n: PlanetState(n, p.longitude, p.speed) for n, p in pos.items()})
    return utc, chart


def main():
    out = []
    out.append("// AUTO-GENERATED by cpp/tools/gen_golden.py -- do not edit by hand.")
    out.append("// Values produced by the Python engine validated against Swiss Ephemeris.")
    out.append("#pragma once")
    out.append("#include <array>")
    out.append("#include <string>")
    out.append("#include <vector>")
    out.append("")
    out.append("namespace vyas::golden {")
    out.append("")
    out.append("struct GoldenCase {")
    out.append("    std::string label;")
    out.append("    int year, month, day, hour, minute;")
    out.append("    double tz_hours, latitude, lon_east;")
    out.append("    double ayanamsa;")
    out.append("    double ascendant;")
    out.append("    std::array<double, 9> lon;   // Sun..Ketu")
    out.append("    std::array<double, 9> speed;")
    out.append("    std::array<int, 9> sign_index;")
    out.append("    std::array<int, 9> nakshatra;")
    out.append("    std::array<int, 9> pada;")
    out.append("    std::array<int, 9> d9_sign;")
    out.append("    std::array<int, 9> d10_sign;")
    out.append("    std::array<int, 9> d30_sign;")
    out.append("    std::array<int, 9> d60_sign;")
    out.append("    std::string dasha_balance;")
    out.append("    std::array<int, 12> sav;")
    out.append("};")
    out.append("")
    body = []
    order = ["Sun", "Moon", "Mars", "Mercury", "Jupiter", "Venus", "Saturn", "Rahu", "Ketu"]
    for label, local_dt, tz, lat, lon in CASES:
        utc, chart = chart_for(local_dt, tz, lat, lon)
        ay = ephem.ayanamsa_deg(ephem.julian_day_tt(utc))
        dsh = dasha.VimshottariDasha(chart.planets["Moon"].longitude, utc)
        av = ashtakavarga.compute_ashtakavarga(
            {n: p.sign_index for n, p in chart.planets.items()}, chart.ascendant_sign)
        lines = []
        lines.append("    {")
        lines.append('        "%s", %d, %d, %d, %d, %d, %.6f, %.6f, %.6f,' % (
            label, local_dt.year, local_dt.month, local_dt.day, local_dt.hour,
            local_dt.minute, tz, lat, lon))
        lines.append("        %.12f, %.12f," % (ay, chart.ascendant_longitude))
        lines.append("        { " + ", ".join("%.12f" % chart.planets[n].longitude for n in order) + " },")
        lines.append("        { " + ", ".join("%.12f" % chart.planets[n].speed for n in order) + " },")
        lines.append("        { " + ", ".join(str(chart.planets[n].sign_index) for n in order) + " },")
        lines.append("        { " + ", ".join(str(chart.planets[n].nakshatra_index) for n in order) + " },")
        lines.append("        { " + ", ".join(str(chart.planets[n].pada) for n in order) + " },")
        vd = {n: varga.calculate_vargas_detailed(chart.planets[n].longitude) for n in order}
        lines.append("        { " + ", ".join(str(vd[n]["D9"].sign_index) for n in order) + " },")
        lines.append("        { " + ", ".join(str(vd[n]["D10"].sign_index) for n in order) + " },")
        lines.append("        { " + ", ".join(str(vd[n]["D30"].sign_index) for n in order) + " },")
        lines.append("        { " + ", ".join(str(vd[n]["D60"].sign_index) for n in order) + " },")
        lines.append('        "%s",' % dsh.balance_str)
        lines.append("        { " + ", ".join(str(x) for x in av["sav"]) + " },")
        lines.append("    },")
        body.append("\n".join(lines))
    out.append("inline const std::vector<GoldenCase> kCases = {")
    out.append("\n".join(body))
    out.append("};")
    out.append("")
    out.append("}  // namespace vyas::golden")
    print("\n".join(out))


if __name__ == "__main__":
    main()
