def patch_file(p):
    if not os.path.exists(p):
        return
    with open(p, 'r', encoding='utf-8') as f:
        c = f.read()

    # Find start of askSage
    m_ask = c.find('askSage(query, activeChart) {')
    if m_ask == -1:
        print("askSage not found in:", p)
        return

    # Find the backend proxy comment
    m_proxy = c.find('// 1. Try PHP Backend Proxy First', m_ask)
    if m_proxy == -1:
        print("PHP Backend Proxy not found in:", p)
        return

    # Find where if (isPrashnaMode) begins
    m_if = c.find('if (isPrashnaMode) {', m_ask, m_proxy)
    if m_if == -1:
        print("if (isPrashnaMode) not found in:", p)
        return

    # Replace from m_if up to m_proxy
    c = c[:m_if] + PROMPT_BODY.strip() + '\n\n            ' + c[m_proxy:]

    # Also fix generateDynamicLocalReply if it contains वत्स!
    c = c.replace(
        'वत्स! चूंकि तुमने अपनी जन्म पत्रिका प्रविष्ट नहीं की है',
        'सादर प्रणाम! चूंकि आपने अपनी जन्म पत्रिका प्रविष्ट नहीं की है'
    )
    c = c.replace(
        'तुम्हारे प्रश्न पूछने के इस पावन क्षण',
        'आपके प्रश्न पूछने के इस पावन क्षण'
    )

    with open(p, 'w', encoding='utf-8') as f:
        f.write(c)
    print("✓ Successfully patched askSage in:", p)

