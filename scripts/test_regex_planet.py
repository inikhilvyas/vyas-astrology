import re

text = """
सूर्य (Sun): वृश्चिक 07°42'00" (नक्षत्र: अनुराधा (4), भाव 8, स्थिति: मित्र)
चन्द्र (Moon): वृश्चिक 14°38'00" (नक्षत्र: अनुराधा (4), भाव 8, स्थिति: नीच)
मंगल (Mars): मकर 12°09'00" (नक्षत्र: श्रवण (1), भाव 10, स्थिति: उच्च)
"""

pattern = r'मंगल[^:]*:\s*([^\s\d]+)\s+[^()]*\(.*?भाव\s*(\d+).*?स्थिति:\s*([^)]+)\)'
m = re.search(pattern, text)
if m:
    print('Matched:', m.groups())
else:
    print('Failed to match')

